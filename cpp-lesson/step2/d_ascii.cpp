#include <iostream>
int main() {
    char a {'a'}, b {'b'}, A {'A'}, B {'B'}, zero {'0'}, sp {' '}, nl {'\n'};
    std::cout << "'a' = " << (int)a << "\n";
    std::cout << "'b' = " << (int)b << "\n";
    std::cout << "'A' = " << (int)A << "\n";
    std::cout << "'B' = " << (int)B << "\n";
    std::cout << "'0' = " << (int)zero << "\n";
    std::cout << "' ' = " << (int)sp << "\n";
    std::cout << "'\\n'= " << (int)nl << "\n";
}
